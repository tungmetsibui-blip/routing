import json
from router import Router
from packet import Packet


class DVrouter(Router):
    """Distance vector routing protocol implementation.

    Add your own class fields and initialization code (e.g. to create forwarding table
    data structures). See the `Router` base class for docstrings of the methods to
    override.
    """

    INFINITY = 16

    def __init__(self, addr, heartbeat_time):
        Router.__init__(self, addr)  # Initialize base class - DO NOT REMOVE
        self.heartbeat_time = heartbeat_time
        self.last_time = 0
        # TODO
        #   add your own class fields and initialization code here
        self.port_info = {}         # {port: (endpoint, cost)}
        self.neighbor_dvs = {}      # {neighbor_addr: {dest: cost}}
        self.dv = {self.addr: 0}    # {dest: cost}
        self.forwarding_table = {}  # {dest: port}

    def _recompute_dv(self):
        """Recompute distance vector and forwarding table."""
        all_dests = {self.addr}
        for endpoint, _ in self.port_info.values():
            all_dests.add(endpoint)
        for nbr_dv in self.neighbor_dvs.values():
            all_dests.update(nbr_dv.keys())

        new_dv = {self.addr: 0}
        new_ft = {}

        for dest in all_dests:
            if dest == self.addr:
                continue

            min_cost = self.INFINITY
            best_port = None

            for port, (nbr, link_cost) in self.port_info.items():
                cost_via_nbr = self.INFINITY
                if dest == nbr:
                    cost_via_nbr = link_cost
                elif nbr in self.neighbor_dvs and dest in self.neighbor_dvs[nbr]:
                    cost_via_nbr = link_cost + self.neighbor_dvs[nbr][dest]

                if cost_via_nbr < min_cost:
                    min_cost = cost_via_nbr
                    best_port = port

            if min_cost < self.INFINITY:
                new_dv[dest] = min_cost
                new_ft[dest] = best_port

        changed = (new_dv != self.dv) or (new_ft != self.forwarding_table)
        self.dv = new_dv
        self.forwarding_table = new_ft
        return changed

    def _broadcast_dv(self):
        """Broadcast distance vector to neighbors with Poison Reverse."""
        for port, (nbr, _) in self.port_info.items():
            custom_dv = {}
            for dest, cost in self.dv.items():
                if dest != self.addr and self.forwarding_table.get(dest) == port and dest != nbr:
                    custom_dv[dest] = self.INFINITY
                else:
                    custom_dv[dest] = cost

            pkt = Packet(Packet.ROUTING, self.addr, nbr, content=json.dumps(custom_dv))
            self.send(port, pkt)

    def handle_packet(self, port, packet):
        """Process incoming packet."""
        # TODO
        if packet.is_traceroute:
            # Hint: this is a normal data packet
            # If the forwarding table contains packet.dst_addr
            #   send packet based on forwarding table, e.g., self.send(port, packet)
            if packet.dst_addr in self.forwarding_table:
                self.send(self.forwarding_table[packet.dst_addr], packet)
        else:
            # Hint: this is a routing packet generated by your routing protocol
            # If the received distance vector is different
            #   update the local copy of the distance vector
            #   update the distance vector of this router
            #   update the forwarding table
            #   broadcast the distance vector of this router to neighbors
            if port not in self.port_info:
                return
            nbr_addr = packet.src_addr
            received_dv = json.loads(packet.content)
            if self.neighbor_dvs.get(nbr_addr) != received_dv:
                self.neighbor_dvs[nbr_addr] = received_dv
                if self._recompute_dv():
                    self._broadcast_dv()

    def handle_new_link(self, port, endpoint, cost):
        """Handle new link."""
        # TODO
        #   update the distance vector of this router
        #   update the forwarding table
        #   broadcast the distance vector of this router to neighbors
        self.port_info[port] = (endpoint, cost)
        if endpoint not in self.neighbor_dvs:
            self.neighbor_dvs[endpoint] = {endpoint: 0}
        self._recompute_dv()
        self._broadcast_dv()

    def handle_remove_link(self, port):
        """Handle removed link."""
        # TODO
        #   update the distance vector of this router
        #   update the forwarding table
        #   broadcast the distance vector of this router to neighbors
        if port in self.port_info:
            endpoint, _ = self.port_info.pop(port)
            still_connected = any(ep == endpoint for ep, _ in self.port_info.values())
            if not still_connected:
                self.neighbor_dvs.pop(endpoint, None)
            self._recompute_dv()
            self._broadcast_dv()

    def handle_time(self, time_ms):
        """Handle current time."""
        if time_ms - self.last_time >= self.heartbeat_time:
            self.last_time = time_ms
            # TODO
            #   broadcast the distance vector of this router to neighbors
            self._broadcast_dv()

    def __repr__(self):
        """Representation for debugging in the network visualizer."""
        # TODO
